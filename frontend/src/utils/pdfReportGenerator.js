import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';

/**
 * PDF Generator for iPark UMAK - OHSO Security & Admin Reports
 * Uses professional corporate/university styling (UMak Blue & Gold palette, high contrast, clean headers)
 * No generic/sloppy AI-looking placeholders.
 */

const UMAK_NAVY = [10, 31, 92]; // #0A1F5C
const UMAK_ORANGE = [245, 130, 31]; // #F5821F
const SLATE_DARK = [30, 41, 59];
const SLATE_MUTED = [100, 116, 139];

const formatTimestamp = (ts) => {
  if (!ts) return 'N/A';
  const d = new Date(ts * 1000);
  return d.toLocaleString('en-US', {
    timeZone: 'Asia/Manila',
    month: 'short',
    day: 'numeric',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    hour12: true
  });
};

const formatDateOnly = (ts) => {
  if (!ts) return 'N/A';
  const d = typeof ts === 'number' ? new Date(ts * 1000) : new Date(ts);
  return d.toLocaleDateString('en-US', {
    timeZone: 'Asia/Manila',
    month: 'short',
    day: 'numeric',
    year: 'numeric'
  });
};

export const generatePDFReport = ({ type, title, range, rows, adminName = 'OHSO Administrator' }) => {
  const doc = new jsPDF({
    orientation: type === 'audit' || type === 'stickers' || type === 'guests' ? 'landscape' : 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  // Top University Banner & Header
  doc.setFillColor(...UMAK_NAVY);
  doc.rect(0, 0, pageWidth, 28, 'F');

  // Accent Gold Line
  doc.setFillColor(...UMAK_ORANGE);
  doc.rect(0, 28, pageWidth, 2, 'F');

  // University Header Typography
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text('UNIVERSITY OF MAKATI', 14, 12);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(220, 230, 250);
  doc.text('Office of Health, Safety and Security (OHSO) - Campus Parking & Mobility System (iPark UMAK)', 14, 18);
  doc.text('J.P. Rizal Ext., West Rembo, Taguig City, Philippines', 14, 23);

  // Document Title & Metadata Box
  doc.setTextColor(...SLATE_DARK);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.text(title.toUpperCase(), 14, 40);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(...SLATE_MUTED);
  doc.text(`Reporting Period: ${range.from} to ${range.to} (${range.days || 'N/A'} days)`, 14, 46);
  doc.text(`Generated By: ${adminName} | Date: ${formatTimestamp(Math.floor(Date.now() / 1000))}`, 14, 51);

  // Status / Count pill
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...UMAK_NAVY);
  doc.text(`Total Records: ${rows.length}`, pageWidth - 14, 46, { align: 'right' });

  // Divider
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.5);
  doc.line(14, 56, pageWidth - 14, 56);

  // Table Columns & Data Mapping
  let tableHead = [];
  let tableBody = [];

  if (type === 'stickers') {
    tableHead = [['#', 'Date', 'Applicant Name', 'Student / ID No.', 'Email', 'Vehicle', 'Plate No.', 'Payment', 'Status', 'Sticker No.']];
    tableBody = rows.map((r, i) => [
      i + 1,
      formatDateOnly(r.ts),
      r.applicant_name || 'N/A',
      r.student_id_num || 'N/A',
      r.email || 'N/A',
      `${r.vehicle_type?.toUpperCase() || ''} (${r.vehicle_make || ''})`,
      r.plate_number || 'N/A',
      r.payment_status?.toUpperCase() || 'UNPAID',
      r.status?.toUpperCase() || 'PENDING',
      r.sticker_number || '-'
    ]);
  } else if (type === 'revenue') {
    tableHead = [['#', 'Date', 'Applicant Name', 'Student / ID', 'Vehicle', 'Method', 'Payment Ref', 'Status', 'Sticker No.', 'Amount']];
    let totalRevenue = 0;
    tableBody = rows.map((r, i) => {
      const amt = Number(r.amount) || 200;
      if (r.payment_status === 'paid') totalRevenue += amt;
      return [
        i + 1,
        formatDateOnly(r.ts),
        r.applicant_name || 'N/A',
        r.student_id_num || 'N/A',
        `${r.vehicle_type || ''} (${r.plate_number || ''})`,
        (r.payment_method || 'GCash').toUpperCase(),
        r.payment_ref_no || '-',
        r.payment_status?.toUpperCase() || 'PENDING',
        r.sticker_number || '-',
        `PHP ${amt.toFixed(2)}`
      ];
    });
    tableBody.push([
      '', '', '', '', '', '', '', '',
      'TOTAL VERIFIED:',
      `PHP ${totalRevenue.toFixed(2)}`
    ]);
  } else if (type === 'guests') {
    tableHead = [['#', 'Event Date', 'Guest Name', 'Guest Email', 'Event Title', 'Schedule', 'Venue', 'Role', 'Plate No.', 'Pass Code', 'Status']];
    tableBody = rows.map((r, i) => [
      i + 1,
      r.event_date || 'N/A',
      r.guest_name || 'N/A',
      r.email || 'N/A',
      r.event_name || 'N/A',
      `${r.time_start || ''} - ${r.time_end || ''}`,
      r.building_room || 'HPSB',
      r.requestee_role || 'Visitor',
      r.plate_number || 'N/A',
      r.pass_code || '-',
      r.status?.toUpperCase() || 'PENDING'
    ]);
  } else if (type === 'users') {
    tableHead = [['#', 'Registered Date', 'Account Name', 'UMak Email', 'Role', 'Verified', 'Failed Attempts', 'Security Status']];
    tableBody = rows.map((r, i) => [
      i + 1,
      formatDateOnly(r.ts),
      r.name || 'N/A',
      r.email || 'N/A',
      r.role?.toUpperCase() || 'STUDENT',
      r.is_verified ? 'YES' : 'NO',
      r.failed_login_attempts || 0,
      r.is_locked ? 'LOCKED' : 'ACTIVE'
    ]);
  } else if (type === 'audit') {
    const cleanAuditDesc = (desc) => {
      if (!desc) return '';
      return desc
        .replace(/^User signed in successfully\s*\([^)]*\)$/i, 'Signed in with password')
        .replace(/^Signed in successfully via official Google SSO\s*\([^)]*\)$/i, 'Signed in with Google SSO')
        .replace(/^(?:Exported official|Generated)\s*(?:PDF|CSV)?\s*"?([^"()]+)"?\s*(?:covering|for)?\s*[\d-]*\s*(?:to)?\s*[\d-]*\s*\(\d+\s*records\)$/i, 'Generated $1')
        .trim();
    };

    tableHead = [['#', 'Timestamp (PHT)', 'Category', 'Action Event', 'Actor / User', 'Description', 'Status']];
    tableBody = rows.map((r, i) => [
      i + 1,
      formatTimestamp(r.ts),
      r.category?.toUpperCase() || 'SYSTEM',
      r.action || 'ACTION',
      r.actorEmail || 'Anonymous/System',
      cleanAuditDesc(r.description),
      r.status?.toUpperCase() || 'SUCCESS'
    ]);
  }

  // Draw autotable
  autoTable(doc, {
    startY: 60,
    head: tableHead,
    body: tableBody,
    theme: 'grid',
    styles: {
      fontSize: type === 'audit' ? 7.5 : 8,
      cellPadding: 2,
      font: 'helvetica',
      textColor: SLATE_DARK,
      lineColor: [226, 232, 240],
      lineWidth: 0.2
    },
    headStyles: {
      fillColor: UMAK_NAVY,
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      halign: 'left'
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252]
    },
    didDrawPage: (data) => {
      // Professional Footer on every page
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(7.5);
      doc.setTextColor(...SLATE_MUTED);

      // Left Footer: System Signature
      doc.text(
        'iPark UMAK System-Generated Official Audit Report - Tamper Evident Verification Log',
        14,
        pageHeight - 8
      );

      // Right Footer: Page counter
      const pageStr = `Page ${doc.internal.getNumberOfPages()}`;
      doc.text(pageStr, pageWidth - 14, pageHeight - 8, { align: 'right' });

      // Bottom colored bar
      doc.setFillColor(...UMAK_NAVY);
      doc.rect(0, pageHeight - 3, pageWidth, 3, 'F');
    }
  });

  const fileName = `iPark_UMAK_${type}_report_${range.from}_to_${range.to}.pdf`;
  doc.save(fileName);
};
